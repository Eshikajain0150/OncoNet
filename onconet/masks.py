"""Study-specific binary reference masks (manuscript Section 3.1.1.1).

Reference masks are generated by a deterministic, parameter-documented procedure that
anyone can rerun. Every
archive image is a single-cell crop centred on one leukocyte / blast surrounded by
erythrocytes and background. On the 256x256 un-normalised image:

1. Nucleus: 3-class multi-Otsu on the smoothed green channel (Romanowsky-stained
   chromatin absorbs green most strongly). The darkest class is kept, opened, restricted to
   components near the image centre, closed and hole-filled.
2. Whole cell (nucleus + cytoplasm): OpenCV GrabCut (5 iterations, RNG seed 42). Seeds:
   the eroded nucleus is definite foreground; pixels within 0.5*r of the nucleus convex
   hull are probable foreground (r = equivalent radius of the hull); pixels farther than
   1.1*r + 15 px and black padding pixels are definite background; everything else is
   probable background.
3. Post-processing: opening (9 px), keep the component that overlaps the nucleus, fill holes,
   enforce nucleus within cell.

The masks are reference targets for this study, not expert clinical annotations.
``scripts/02_make_masks.py`` writes a QC montage for visual inspection.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass

import cv2
import numpy as np
from scipy.ndimage import binary_fill_holes
from skimage.filters import threshold_multiotsu


@dataclass
class MaskParams:
    blur_ksize: int = 5
    nucleus_open: int = 5
    nucleus_close: int = 5
    nucleus_min_area: int = 40
    nucleus_max_center_dist: float = 0.30   # fraction of image size
    pr_fg_factor: float = 0.5
    bg_factor: float = 1.1
    bg_offset_px: int = 15
    min_pr_fg_px: int = 8
    padding_level: float = 0.10             # max(R,G,B) below this = black padding
    grabcut_iters: int = 5
    cell_open: int = 9
    seed: int = 42

    def as_dict(self):
        return asdict(self)


def _ellipse(k):
    return cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k))


def _central_components(binary, max_dist_frac, min_area):
    n, lab, st, cen = cv2.connectedComponentsWithStats(binary.astype(np.uint8), connectivity=8)
    if n <= 1:
        return np.zeros_like(binary, bool)
    h, w = binary.shape
    d = np.linalg.norm(cen[1:] - np.array([w / 2, h / 2]), axis=1) / max(h, w)
    a = st[1:, cv2.CC_STAT_AREA]
    ok = (d <= max_dist_frac) & (a >= min_area)
    if not ok.any():
        ok[np.argmax(a / (1 + 10 * d))] = True
    return np.isin(lab, np.where(ok)[0] + 1)


def nucleus_mask(img: np.ndarray, p: MaskParams = MaskParams()) -> np.ndarray:
    f = cv2.GaussianBlur(img, (p.blur_ksize, p.blur_ksize), 0).astype(np.float32) / 255.0
    G = f[..., 1]
    t = threshold_multiotsu(G, classes=3)
    nuc = cv2.morphologyEx((G < t[0]).astype(np.uint8), cv2.MORPH_OPEN, _ellipse(p.nucleus_open)).astype(bool)
    nuc = _central_components(nuc, p.nucleus_max_center_dist, p.nucleus_min_area)
    nuc = cv2.morphologyEx(nuc.astype(np.uint8), cv2.MORPH_CLOSE, _ellipse(p.nucleus_close)).astype(bool)
    return binary_fill_holes(nuc)


def reference_masks(img: np.ndarray, p: MaskParams = MaskParams()):
    """img: RGB uint8 (256x256) -> (cell_mask, nucleus_mask) boolean arrays."""
    h, w = img.shape[:2]
    nuc = nucleus_mask(img, p)
    pad = img.max(-1) < p.padding_level * 255
    hull = np.zeros((h, w), np.uint8)
    if nuc.any():
        cs, _ = cv2.findContours(nuc.astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        cv2.fillPoly(hull, [cv2.convexHull(np.concatenate(cs))], 1)
    else:
        cv2.circle(hull, (w // 2, h // 2), 20, 1, -1)
    r = np.sqrt(hull.sum() / np.pi)
    dist = cv2.distanceTransform((1 - hull).astype(np.uint8), cv2.DIST_L2, 5)
    gc = np.full((h, w), cv2.GC_PR_BGD, np.uint8)
    gc[dist <= max(p.pr_fg_factor * r, p.min_pr_fg_px)] = cv2.GC_PR_FGD
    gc[dist > p.bg_factor * r + p.bg_offset_px] = cv2.GC_BGD
    gc[pad] = cv2.GC_BGD
    gc[cv2.erode(nuc.astype(np.uint8), _ellipse(5)) > 0] = cv2.GC_FGD
    bgd, fgd = np.zeros((1, 65), np.float64), np.zeros((1, 65), np.float64)
    cv2.setRNGSeed(p.seed)
    try:
        cv2.grabCut(cv2.cvtColor(img, cv2.COLOR_RGB2BGR), gc, None, bgd, fgd, p.grabcut_iters,
                    cv2.GC_INIT_WITH_MASK)
        cell = (gc == cv2.GC_FGD) | (gc == cv2.GC_PR_FGD)
    except cv2.error:  # degenerate seeds (e.g. no background sample) -> fall back to the hull region
        cell = dist <= max(p.pr_fg_factor * r, p.min_pr_fg_px)
    cell = cv2.morphologyEx((cell & ~pad).astype(np.uint8), cv2.MORPH_OPEN, _ellipse(p.cell_open))
    n, lab = cv2.connectedComponents(cell, connectivity=8)
    if n > 1:
        if nuc.any():
            ids, cnt = np.unique(lab[nuc & (lab > 0)], return_counts=True)
            keep = ids[np.argmax(cnt)] if len(ids) else 1
        else:
            keep = lab[h // 2, w // 2] or 1
        cell = lab == keep
    cell = binary_fill_holes(cell.astype(bool) | nuc)
    return cell, nuc & cell
